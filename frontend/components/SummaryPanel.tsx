"use client";

import { useEffect, useRef, useState } from "react";

import type { StepState } from "@/components/ProgressSteps";

import { ApiError, getHealth, summarizeReport } from "@/lib/api";
import type { EvidencePassage, Strategy, SummaryResponse, ValidationReport } from "@/types/api";

const STRATEGIES: { value: Strategy; label: string; description: string }[] = [
  { value: "rag", label: "RAG-enhanced", description: "Instructions, reviewed examples and cited reference passages" },
  { value: "few_shot", label: "Few-shot", description: "Instructions and reviewed examples, no references" },
  { value: "zero_shot", label: "Zero-shot", description: "Instructions only" },
];

type State =
  | { kind: "idle" }
  | { kind: "loading" }
  | { kind: "ready"; response: SummaryResponse }
  | { kind: "error"; message: string };

const VALIDATION_STEP: Record<SummaryResponse["validation"]["status"], StepState> = {
  passed: { status: "done", detail: "Checks passed" },
  passed_with_warnings: { status: "warning", detail: "Passed with warnings" },
  failed: { status: "error", detail: "Failed safety checks" },
};

export function SummaryPanel({ file, onStateChange }: { file: File; onStateChange?: (state: StepState) => void }) {
  const [strategy, setStrategy] = useState<Strategy>("rag");
  const [state, setState] = useState<State>({ kind: "idle" });
  const [llmConfigured, setLlmConfigured] = useState<boolean | null>(null);
  const controllerRef = useRef<AbortController | null>(null);

  useEffect(() => {
    const controller = new AbortController();
    getHealth(controller.signal)
      .then((health) => {
        setLlmConfigured(health.llm.api_key_configured);
        if (!health.llm.api_key_configured) onStateChange?.({ status: "pending", detail: "API key not configured" });
      })
      .catch(() => {
        // The status panel reports connectivity problems; leave the button usable.
      });
    return () => controller.abort();
  }, [onStateChange]);

  const generate = async () => {
    controllerRef.current?.abort();
    const controller = new AbortController();
    controllerRef.current = controller;
    setState({ kind: "loading" });
    onStateChange?.({ status: "active", detail: "Generating…" });
    try {
      const response = await summarizeReport(file, strategy, controller.signal);
      setState({ kind: "ready", response });
      onStateChange?.(VALIDATION_STEP[response.validation.status]);
    } catch (error) {
      if (controller.signal.aborted) return;
      setState({
        kind: "error",
        message: error instanceof ApiError ? error.message : "The summary could not be generated.",
      });
      onStateChange?.({ status: "error", detail: "Not generated" });
    }
  };

  useEffect(() => () => controllerRef.current?.abort(), []);

  return (
    <section aria-labelledby="summary-heading" className="rounded-2xl border border-border bg-surface p-6 shadow-sm">
      <h3 id="summary-heading" className="text-lg font-semibold">
        Plain-language summary
      </h3>
      <p className="mt-1 text-sm text-muted">
        Generated by Gemini from the test results above, then checked automatically. Only the recognised test
        results are sent to the model, not the report text.
      </p>

      <fieldset className="mt-4" disabled={state.kind === "loading"}>
        <legend className="text-sm font-medium">Prompting strategy</legend>
        <div className="mt-2 grid gap-2 sm:grid-cols-3">
          {STRATEGIES.map((option) => (
            <label
              key={option.value}
              className={`cursor-pointer rounded-lg border p-3 text-sm transition-colors has-[:focus-visible]:outline-2 has-[:focus-visible]:outline-brand ${
                strategy === option.value ? "border-brand bg-brand-soft" : "border-border hover:bg-background"
              }`}
            >
              <input
                type="radio"
                name="strategy"
                value={option.value}
                checked={strategy === option.value}
                onChange={() => setStrategy(option.value)}
                className="sr-only"
              />
              <span className="font-medium">{option.label}</span>
              <span className="mt-0.5 block text-xs text-muted">{option.description}</span>
            </label>
          ))}
        </div>
      </fieldset>

      {llmConfigured === false && (
        <p className="mt-4 rounded-lg border border-warning-border bg-warning-bg px-3 py-2 text-sm text-warning-fg">
          Summaries need a Gemini API key. Add <code className="font-mono">GEMINI_API_KEY</code> to{" "}
          <code className="font-mono">.env</code> and restart the backend. The test results and reference information
          below work without it.
        </p>
      )}

      <button
        type="button"
        onClick={generate}
        disabled={state.kind === "loading" || llmConfigured === false}
        className="mt-4 rounded-lg bg-brand px-4 py-2 text-sm font-semibold text-white transition-colors hover:bg-brand-strong focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-brand disabled:cursor-not-allowed disabled:opacity-50 dark:text-background"
      >
        {state.kind === "loading" ? "Generating…" : state.kind === "ready" ? "Generate again" : "Generate summary"}
      </button>

      <div role="status" aria-live="polite" aria-busy={state.kind === "loading"} className="mt-4">
        {state.kind === "loading" && (
          <p className="flex items-center gap-2 text-sm text-muted">
            <span aria-hidden="true" className="size-2.5 animate-pulse rounded-full bg-brand" />
            Extracting, retrieving references and asking the model. This can take up to a minute.
          </p>
        )}
        {state.kind === "error" && (
          <p role="alert" className="rounded-lg border border-danger/40 px-3 py-2 text-sm text-danger">
            {state.message}
          </p>
        )}
      </div>

      {state.kind === "ready" && <SummaryResult key={state.response.prompt_sha256} response={state.response} />}
    </section>
  );
}

function SummaryResult({ response }: { response: SummaryResponse }) {
  const failed = response.validation.status === "failed";
  const [revealed, setRevealed] = useState(false);
  const passages = new Map(response.evidence.map((p) => [p.citation_id, p]));

  return (
    <div className="space-y-6">
      <ValidationBanner validation={response.validation} />

      {failed && !revealed ? (
        <button
          type="button"
          onClick={() => setRevealed(true)}
          className="rounded-lg border border-border px-3 py-1.5 text-sm hover:bg-background focus-visible:outline-2 focus-visible:outline-brand"
        >
          Show the rejected output for review
        </button>
      ) : (
        <div className={`space-y-6 ${failed ? "rounded-xl border-2 border-dashed border-danger/50 p-4" : ""}`}>
          {failed && <p className="text-sm font-semibold text-danger">Rejected output — shown for review only.</p>}

          <p className="text-base leading-7">{response.output.summary}</p>

          <div>
            <h4 className="font-semibold">Your results explained</h4>
            <ul className="mt-3 space-y-3">
              {response.output.test_explanations.map((item, index) => (
                <li key={`${item.test_name}-${index}`} className="rounded-lg bg-background p-4">
                  <p className="font-medium">
                    {item.test_name}:{" "}
                    <span className="font-mono">
                      {item.reported_value}
                      {item.unit ? ` ${item.unit}` : ""}
                    </span>
                    <span className="text-sm font-normal text-muted">
                      {" "}
                      · range {item.reference_range ?? "not printed"}
                    </span>
                  </p>
                  <p className="mt-1 text-sm leading-6">
                    {item.explanation} <Citations ids={item.citation_ids} passages={passages} />
                  </p>
                </li>
              ))}
            </ul>
          </div>

          {response.output.reported_abnormalities.length > 0 && (
            <ListBlock title="Results outside the printed range">
              {response.output.reported_abnormalities.map((item) => (
                <li key={item.test_name}>
                  <span className="font-medium">{item.test_name}</span>{" "}
                  <span className="rounded bg-warning-bg px-1.5 py-0.5 text-xs text-warning-fg">
                    {item.basis === "report_flag" ? "Flagged by the lab" : "Outside printed range (not flagged)"}
                  </span>
                  <span className="block text-muted">{item.description}</span>
                </li>
              ))}
            </ListBlock>
          )}

          {response.output.uncertainties.length > 0 && (
            <ListBlock title="Limitations and uncertainties">
              {response.output.uncertainties.map((text) => (
                <li key={text}>{text}</li>
              ))}
            </ListBlock>
          )}

          <ListBlock title="Questions to ask your healthcare professional">
            {response.output.questions_for_doctor.map((text) => (
              <li key={text}>{text}</li>
            ))}
          </ListBlock>

          {response.output.evidence_citations.length > 0 && (
            <div>
              <h4 className="font-semibold">Sources</h4>
              <ol className="mt-2 space-y-2 text-sm">
                {response.output.evidence_citations.map((citation) => {
                  const passage = passages.get(citation.citation_id);
                  return (
                    <li key={citation.citation_id} id={`source-${citation.citation_id}`} className="rounded-lg bg-background p-3">
                      <span className="mr-2 rounded bg-brand-soft px-1.5 py-0.5 font-mono text-xs text-brand-strong">
                        {citation.citation_id}
                      </span>
                      {citation.supports}
                      {passage && (
                        <span className="mt-1 block text-xs text-muted">
                          {passage.title} — {passage.section} ·{" "}
                          <a href={passage.url} target="_blank" rel="noopener noreferrer" className="underline">
                            {passage.attribution}
                          </a>
                        </span>
                      )}
                    </li>
                  );
                })}
              </ol>
            </div>
          )}

          <p className="rounded-lg border border-warning-border bg-warning-bg px-3 py-2 text-sm text-warning-fg">
            {response.output.safety_notice}
          </p>
        </div>
      )}

      <p className="text-xs text-muted">{response.disclaimer}</p>
      <p className="text-xs text-muted">
        {response.model} · strategy {response.strategy} · prompt {response.prompt_version} (
        {response.prompt_sha256.slice(0, 8)}) · {response.usage.total_tokens ?? "?"} tokens ·{" "}
        {(response.latency_ms / 1000).toFixed(1)} s
      </p>
    </div>
  );
}

function Citations({ ids, passages }: { ids: string[]; passages: Map<string, EvidencePassage> }) {
  if (ids.length === 0) return null;
  return (
    <>
      {ids.map((id) => (
        <a
          key={id}
          href={`#source-${id}`}
          title={passages.get(id)?.title}
          className="mr-1 rounded bg-brand-soft px-1 font-mono text-xs text-brand-strong no-underline"
        >
          {id}
        </a>
      ))}
    </>
  );
}

function ListBlock({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <div>
      <h4 className="font-semibold">{title}</h4>
      <ul className="mt-2 list-disc space-y-1.5 pl-5 text-sm leading-6">{children}</ul>
    </div>
  );
}

const BANNER = {
  passed: {
    className: "border-brand/40 bg-brand-soft text-brand-strong",
    title: "Automated checks passed",
  },
  passed_with_warnings: {
    className: "border-warning-border bg-warning-bg text-warning-fg",
    title: "Automated checks passed with warnings",
  },
  failed: {
    className: "border-danger/50 bg-danger/10 text-danger",
    title: "This summary failed safety checks and is hidden",
  },
} as const;

function ValidationBanner({ validation }: { validation: ValidationReport }) {
  const style = BANNER[validation.status];
  return (
    <div className={`rounded-lg border px-4 py-3 text-sm ${style.className}`}>
      <p className="font-semibold">{style.title}</p>
      {validation.issues.length > 0 && (
        <ul className="mt-2 list-disc space-y-1 pl-5">
          {validation.issues.map((issue, index) => (
            <li key={`${issue.code}-${index}`}>
              <span className="font-medium">{issue.severity === "error" ? "Error" : "Warning"}:</span> {issue.message}
            </li>
          ))}
        </ul>
      )}
      <p className="mt-2 text-xs opacity-80">{validation.note}</p>
    </div>
  );
}
